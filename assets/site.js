const LANGUAGE_KEY = "oneshow_lang";
const DEFAULT_LANGUAGE = "zh";
const PUBLIC_DOMAIN = "https://oneshowailab.com";

const getCanonicalPath = () => {
  const path = (location.pathname || "/").trim();
  if (!path || path === "/") return "/";
  if (path.endsWith(".html")) return path;
  if (path.endsWith("/")) return `${path}index.html`;
  return `${path}.html`;
};

const ensureSeoMeta = () => {
  const canonicalHref = `${PUBLIC_DOMAIN}${getCanonicalPath() === "/" ? "/" : getCanonicalPath()}`;

  let canonical = document.querySelector("link[rel='canonical']");
  if (!canonical) {
    canonical = document.createElement("link");
    canonical.setAttribute("rel", "canonical");
    document.head.appendChild(canonical);
  }
  canonical.setAttribute("href", canonicalHref);

  let ogUrl = document.querySelector("meta[property='og:url']");
  if (!ogUrl) {
    ogUrl = document.createElement("meta");
    ogUrl.setAttribute("property", "og:url");
    document.head.appendChild(ogUrl);
  }
  ogUrl.setAttribute("content", canonicalHref);

  let ogSite = document.querySelector("meta[property='og:site_name']");
  if (!ogSite) {
    ogSite = document.createElement("meta");
    ogSite.setAttribute("property", "og:site_name");
    document.head.appendChild(ogSite);
  }
  ogSite.setAttribute("content", "OneShowAILab");
};

const getStoredLanguage = () => {
  const lang = localStorage.getItem(LANGUAGE_KEY);
  return lang === "en" || lang === "zh" ? lang : null;
};

const browserLanguage = () => {
  const lang = (navigator.language || "").toLowerCase();
  return lang.startsWith("en") ? "en" : "zh";
};

const getText = (lang, key) => {
  const parts = key.split(".");
  let current = translations[lang];
  for (const part of parts) {
    if (!current || typeof current !== "object" || !(part in current)) {
      return null;
    }
    current = current[part];
  }
  return typeof current === "string" ? current : null;
};

const getCurrentLanguage = () => {
  const pageLang = getStoredLanguage() || browserLanguage();
  return pageLang || DEFAULT_LANGUAGE;
};

const getActiveNav = () => {
  const path = (location.pathname.split("/").pop() || "index.html");
  return path;
};

const setNavigationActive = () => {
  const current = getActiveNav();
  document.querySelectorAll(".nav-link").forEach((item) => {
    const href = item.getAttribute("href");
    if (href === current) {
      item.classList.add("active");
    }
  });
};

const applyLanguage = (lang) => {
  const activeLang = lang === "en" ? "en" : "zh";
  const page = document.body?.dataset?.page || "home";
  const pageKey = page;

  document.documentElement.lang = activeLang === "zh" ? "zh-CN" : "en";

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (!key) return;

    const resolvedKey = `${pageKey}.${key}`;
    const raw = getText(activeLang, resolvedKey) || getText("zh", resolvedKey);
    if (!raw) return;

    if (el.tagName === "TITLE") {
      document.title = raw;
      return;
    }

    el.textContent = raw;
  });

  document.querySelectorAll("[data-i18n-attr]").forEach((el) => {
    const key = el.getAttribute("data-i18n-attr-key");
    const attr = el.getAttribute("data-i18n-attr");
    if (!key || !attr) return;

    const resolvedKey = `${pageKey}.${key}`;
    const raw = getText(activeLang, resolvedKey) || getText("zh", resolvedKey);
    if (!raw) return;

    el.setAttribute(attr, raw);
  });

  document.querySelectorAll("[data-i18n-global]").forEach((el) => {
    const key = el.getAttribute("data-i18n-global");
    const raw = getText(activeLang, `global.${key}`) || getText("zh", `global.${key}`);
    if (!raw) return;
    el.textContent = raw;
  });

  document.querySelectorAll("[data-i18n-global-attr]").forEach((el) => {
    const key = el.getAttribute("data-i18n-global-attr");
    const attr = el.getAttribute("data-i18n-attr");
    if (!key || !attr) return;
    const raw = getText(activeLang, `global.${key}`) || getText("zh", `global.${key}`);
    if (!raw) return;
    el.setAttribute(attr, raw);
  });

  const menuBtn = document.getElementById("menuBtn");
  if (menuBtn) {
    menuBtn.setAttribute(
      "aria-label",
      getText(activeLang, "global.menu.openAria") || getText("zh", "global.menu.openAria")
    );
  }

  const langToggle = document.getElementById("langToggle");
  if (langToggle) {
    if (activeLang === "zh") {
      langToggle.textContent = getText("zh", "global.lang.showEn") || "EN";
      langToggle.setAttribute(
        "aria-label",
        getText("zh", "global.lang.toEnAria") || "Switch to English"
      );
    } else {
      langToggle.textContent = getText("en", "global.lang.showZh") || "中文";
      langToggle.setAttribute(
        "aria-label",
        getText("en", "global.lang.toZhAria") || "Switch to Chinese"
      );
    }
    langToggle.dataset.currentLang = activeLang;
  }

  localStorage.setItem(LANGUAGE_KEY, activeLang);
};

const initializeNavigation = () => {
  const menuBtn = document.getElementById("menuBtn");
  const nav = document.getElementById("nav");

  if (!menuBtn || !nav) return;

  menuBtn.addEventListener("click", () => {
    nav.classList.toggle("open");
    const expanded = nav.classList.contains("open");
    const activeLang = document.documentElement.lang?.startsWith("en") ? "en" : "zh";
    const key = expanded ? "global.menu.closeAria" : "global.menu.openAria";
    menuBtn.setAttribute("aria-label", getText(activeLang, key) || getText("zh", key));
  });

  document.addEventListener("click", (e) => {
    if (!nav.contains(e.target) && !menuBtn.contains(e.target) && nav.classList.contains("open")) {
      nav.classList.remove("open");
      const activeLang = document.documentElement.lang?.startsWith("en") ? "en" : "zh";
      menuBtn.setAttribute("aria-label", getText(activeLang, "global.menu.openAria") || getText("zh", "global.menu.openAria"));
    }
  });

  nav.querySelectorAll("a").forEach((item) => {
    item.addEventListener("click", () => {
      nav.classList.remove("open");
    });
  });
};

const initializeLanguageSwitch = () => {
  const langToggle = document.getElementById("langToggle");
  if (!langToggle) return;

  langToggle.addEventListener("click", () => {
    const current = langToggle.dataset.currentLang === "en" ? "en" : "zh";
    const next = current === "zh" ? "en" : "zh";
    applyLanguage(next);
  });
};

document.addEventListener("DOMContentLoaded", () => {
  const pageLang = getCurrentLanguage();
  applyLanguage(pageLang);
  setNavigationActive();
  initializeNavigation();
  initializeLanguageSwitch();
  ensureSeoMeta();
});

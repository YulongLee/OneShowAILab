const LANGUAGE_KEY = "oneshow_lang";
const DEFAULT_LANGUAGE = "zh";
const PUBLIC_DOMAIN = "https://oneshowailab.com";

const getCanonicalPath = () => {
  const path = (location.pathname || "/").trim();
  if (!path || path === "/") return "/";
  if (path.endsWith(".html")) return path;
  if (path.endsWith("/")) return `${path}index.html`;
  return `${path}.html`;
};

const ensureSeoMeta = () => {
  const canonicalHref = `${PUBLIC_DOMAIN}${getCanonicalPath() === "/" ? "/" : getCanonicalPath()}`;

  let canonical = document.querySelector("link[rel='canonical']");
  if (!canonical) {
    canonical = document.createElement("link");
    canonical.setAttribute("rel", "canonical");
    document.head.appendChild(canonical);
  }
  canonical.setAttribute("href", canonicalHref);

  let ogUrl = document.querySelector("meta[property='og:url']");
  if (!ogUrl) {
    ogUrl = document.createElement("meta");
    ogUrl.setAttribute("property", "og:url");
    document.head.appendChild(ogUrl);
  }
  ogUrl.setAttribute("content", canonicalHref);

  let ogSite = document.querySelector("meta[property='og:site_name']");
  if (!ogSite) {
    ogSite = document.createElement("meta");
    ogSite.setAttribute("property", "og:site_name");
    document.head.appendChild(ogSite);
  }
  ogSite.setAttribute("content", "OneShowAILab");
};

const getStoredLanguage = () => {
  const lang = localStorage.getItem(LANGUAGE_KEY);
  return lang === "en" || lang === "zh" ? lang : null;
};

const browserLanguage = () => {
  const lang = (navigator.language || "").toLowerCase();
  return lang.startsWith("en") ? "en" : "zh";
};

const getText = (lang, key) => {
  const parts = key.split(".");
  let current = translations[lang];
  for (const part of parts) {
    if (!current || typeof current !== "object" || !(part in current)) {
      return null;
    }
    current = current[part];
  }
  return typeof current === "string" ? current : null;
};

const getCurrentLanguage = () => {
  const pageLang = getStoredLanguage() || browserLanguage();
  return pageLang || DEFAULT_LANGUAGE;
};

const getActiveNav = () => {
  const path = (location.pathname.split("/").pop() || "index.html");
  return path;
};

const setNavigationActive = () => {
  const current = getActiveNav();
  document.querySelectorAll(".nav-link").forEach((item) => {
    const href = item.getAttribute("href");
    if (href === current) {
      item.classList.add("active");
    }
  });
};

